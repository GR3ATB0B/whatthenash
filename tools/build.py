#!/usr/bin/env python3
"""tools/build.py — regenerate derived files. No bundler; run after changing lettering/doodles.

  python3 tools/build.py

1. js/lettering.js   — viewBox sizes for every img/lettering/*.svg (so CSS can set aspect-ratio).
2. index.html        — the inline loader frames (data URIs) between
                       <!-- inline:loader:start --> and <!-- inline:loader:end -->.
"""
import os, re, glob, urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = os.path.join(ROOT, 'img', 'lettering')
D = os.path.join(ROOT, 'img', 'doodles')

def viewbox(path):
    m = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', open(path).read())
    return float(m.group(1)), float(m.group(2))

def data_uri(path):
    svg = open(path).read().strip()
    svg = re.sub(r'<!--.*?-->', '', svg)
    svg = svg.replace('stroke="currentColor"', 'stroke="black"')  # used as a mask; colour comes from CSS
    return 'data:image/svg+xml,' + urllib.parse.quote(svg, safe=" =:/,;'.-")

# 1. lettering dims
names = sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(L, '*.svg')))
rows = ',\n'.join(f"  '{n}': [{w:.0f}, {h:.0f}]" for n in names for (w, h) in [viewbox(os.path.join(L, n + '.svg'))])
open(os.path.join(ROOT, 'js', 'lettering.js'), 'w').write(
    '// js/lettering.js — GENERATED by tools/build.py. Do not edit.\n'
    '// name → [viewBox width, height] for every handwritten SVG in /img/lettering.\n\n'
    f'export const LETTERING = {{\n{rows},\n}};\n')

# 2. inline loader frames
def frame(cls, a, b=None):
    a_uri = data_uri(a); b_uri = data_uri(b or a)
    w, h = viewbox(a)
    return f'.{cls}{{--a:url("{a_uri}");--b:url("{b_uri}");--ar:{w:.0f}/{h:.0f}}}'

css = []
for d in list('0123456789') + ['pct']:
    css.append(frame(f'ld-d{d}', f'{L}/digit-{d}-a.svg', f'{L}/digit-{d}-b.svg'))
css.append(frame('ld-fig', f'{L}/char-still-a.svg', f'{L}/char-walk-right-a.svg'))
css.append(frame('ld-spark', f'{L}/icon-spark-a.svg'))
css.append(frame('ld-plug', f'{D}/plug.TODO.svg'))
css.append(frame('ld-socket', f'{D}/socket.TODO.svg'))
css.append(frame('ld-strip', f'{D}/power-strip.TODO.svg'))
block = '<!-- inline:loader:start -->\n<style id="loader-frames">' + ''.join(css) + '</style>\n<!-- inline:loader:end -->'

idx = os.path.join(ROOT, 'index.html')
html = open(idx).read()
html, n = re.subn(r'<!-- inline:loader:start -->.*?<!-- inline:loader:end -->', lambda m: block, html, flags=re.S)
assert n == 1, 'loader markers not found in index.html'
open(idx, 'w').write(html)
print(f'lettering: {len(names)} · loader frames: {len(block)//1024}KB inline')
